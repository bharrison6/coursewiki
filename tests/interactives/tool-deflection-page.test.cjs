'use strict';
const test = require('node:test'), assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '../..'), folder = path.join(root, 'interactives/tool-deflection');
const page = fs.readFileSync(path.join(root, 'collections/machining/pages/tool-deflection.html'), 'utf8');
const D = require(path.join(folder, 'render.js'));
test('static and print figures are generated by the exact live renderer', () => {
  assert.ok(page.includes(D.staticLesson()));
  assert.match(page, /<noscript>/);
  assert.match(page, /one eighth as much/);
  assert.match(page, /600 GPa/);
});
test('topic assets use the existing loader and Milling track selection', () => {
  assert.match(page, /^@@ID: tool-deflection$/m); assert.match(page, /^@@SECTION: Milling$/m);
  assert.equal((page.match(/data-interactive="tool-deflection"/g) || []).length, 1);
  assert.doesNotMatch(page, /<script\b/);
  const manifest = fs.readFileSync(path.join(folder, 'interactive.conf'), 'utf8');
  const assets = [...manifest.matchAll(/^@@(?:CSS|JS): (.+)$/gm)].flatMap(m => m[1].split(',').map(s => s.trim()));
  assert.deepEqual(assets, ['demo.css', 'model.js', 'render.js', 'demo.js']);
  assets.forEach(f => assert.ok(fs.readdirSync(folder).includes(f)));
  const track = fs.readFileSync(path.join(root, 'tracks/machining-fundamentals.track'), 'utf8');
  assert.match(track, /> Milling[\s\S]*\ntool-deflection\n[\s\S]*> Turning/);
});

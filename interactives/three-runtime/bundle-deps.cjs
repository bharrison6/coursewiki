'use strict';
// Reproduce the checked-in classic-script asset: npm ci --ignore-scripts; npm run build.
// The same local bundle is loaded on web pages and inlined in offline aggregates.
const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
async function main() {
  const dir = path.join(__dirname, 'node_modules', 'three');
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const notices = 'three@' + pkg.version + '\nhttps://www.npmjs.com/package/three\n\n' +
    fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8');
  fs.writeFileSync(path.join(__dirname, 'dependency-licenses.txt'), notices);
  await esbuild.build({
    stdin: { contents: 'export * from "three"; export { OrbitControls } from "three/addons/controls/OrbitControls.js";',
      resolveDir: __dirname, sourcefile: 'module-dependencies.js' },
    outfile: path.join(__dirname, 'three-bundle.js'), bundle: true, minify: true,
    format: 'iife', globalName: 'CourseWikiThree', target: 'es2020',
    legalComments: 'inline', charset: 'utf8',
    banner: { js: '/* Generated by bundle-deps.cjs from the pinned package-lock.json.\n' + notices.replace(/\*\//g, '* /') + '\n*/' },
    footer: { js: 'if(typeof module==="object"&&module.exports)module.exports=CourseWikiThree;' }
  });
}
main().catch(error => { console.error(error); process.exitCode = 1; });

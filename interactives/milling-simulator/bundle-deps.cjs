'use strict';
// Reproduce the checked-in classic-script assets: npm ci --ignore-scripts; npm run build.
// Geometry and worker outputs are local and can be inlined unchanged in print aggregates.
// The renderer is supplied by the shared three-runtime module.
const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
let licenseNotices = '';
async function bundle(contents, globalName, outfile) {
  await esbuild.build({ stdin: { contents, resolveDir: __dirname, sourcefile: 'module-dependencies.js' },
    outfile: path.join(__dirname, outfile), bundle: true, minify: true, format: 'iife', globalName,
    target: 'es2020', legalComments: 'inline', charset: 'utf8',
    banner: { js: '/* Generated by bundle-deps.cjs from the pinned package-lock.json.\n' + licenseNotices.replace(/\*\//g, '* /') + '\n*/' },
    footer: { js: 'if(typeof module==="object"&&module.exports)module.exports=' + globalName + ';' } });
}
(async () => {
  const packages = ['polygon-clipping', 'earcut', 'robust-predicates', 'splaytree'];
  const texts = packages.map(name => {
    const dir = path.join(__dirname, 'node_modules', name), pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-MIT.txt', 'LICENSE-MIT'].find(n => fs.existsSync(path.join(dir, n)));
    var text;
    if (license) text = fs.readFileSync(path.join(dir, license), 'utf8');
    else if (name === 'splaytree') text = fs.readFileSync(path.join(dir, 'Readme.md'), 'utf8').split('## License')[1];
    if (!text) throw new Error('Missing license: ' + name);
    return name + '@' + pkg.version + '\nhttps://www.npmjs.com/package/' + name + '\n\n' + text;
  });
  licenseNotices=texts.join('\n\n----------------------------------------\n\n');
  fs.writeFileSync(path.join(__dirname, 'dependency-licenses.txt'), licenseNotices);
  await bundle('export { default as clip } from "polygon-clipping"; export { default as earcut } from "earcut";', 'CourseWikiMeshLib', 'geometry-bundle.js');
  const worker=await esbuild.build({entryPoints:[path.join(__dirname,'mesh-worker-entry.js')],bundle:true,minify:true,format:'iife',target:'es2020',write:false,legalComments:'inline'});
  fs.writeFileSync(path.join(__dirname,'mesh-worker-source.js'),'/* Local worker, generated by bundle-deps.cjs.\n'+licenseNotices.replace(/\*\//g,'* /')+'\n*/\nvar CourseWikiMillingWorkerSource='+JSON.stringify(worker.outputFiles[0].text)+';\n');
})().catch(e => { console.error(e); process.exitCode = 1; });

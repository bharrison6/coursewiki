async function contextFor(browser, options={}) {
  const context=await browser.newContext(options);
  const fixtureRoot=process.env.COURSEWIKI_STOCK_FIXTURE_ROOT;
  if (fixtureRoot) {
    // Exact generated bytes via Playwright interception: no server or listener.
    const origin=new URL(base).origin;
    const mime={'.html':'text/html','.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml','.png':'image/png','.webp':'image/webp','.jpg':'image/jpeg','.woff2':'font/woff2','.ico':'image/x-icon'};
    await context.route('**/*',async route=>{
      const url=new URL(route.request().url());
      if (url.origin!==origin) return route.abort();
      const parts=decodeURIComponent(url.pathname).split('/').filter(Boolean);
      if (!parts.length || url.pathname.endsWith('/')) parts.push('index.html');
      let file=path.resolve(fixtureRoot);
      for (const part of parts) {
        if (part==='.'||part==='..'||!fs.existsSync(file)||!fs.statSync(file).isDirectory()||!fs.readdirSync(file).includes(part)) return route.fulfill({status:404,body:'Exact fixture path not found'});
        file=path.join(file,part);
      }
      if (!fs.statSync(file).isFile()) return route.fulfill({status:404,body:'Not a file'});
      return route.fulfill({status:200,contentType:mime[path.extname(file)]||'application/octet-stream',body:fs.readFileSync(file)});
    });
  }
  return context;
}

'use strict';
// Embed the screw-and-nut cutaway GLB as a classic-script asset, the same seam end-mill-anatomy uses.
// Input: the output directory of
//   blender -b --factory-startup --python build_model.py -- --out DIR --no-render --cols 96
// The directory is read, never modified. Usage: node bake-model-asset.cjs DIR [--check]
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const EXPECTED = 'c5158a8ff192341dd27851494bca1715a8f68a0263e2c9272750326e8dca8785';
const dir = process.argv[2];
if (!dir) throw new Error('Usage: node bake-model-asset.cjs <build_model.py output directory> [--check]');
const bytes = fs.readFileSync(path.join(dir, 'assembly.glb'));
const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
if (sha256 !== EXPECTED) throw new Error('The 96-column cutaway GLB identity changed: ' + sha256);
const spec = JSON.parse(fs.readFileSync(path.join(dir, 'specification.json'), 'utf8'));
const t = spec.thread, k = spec.kinematics;
if (t.lead_mm !== 5 || t.handedness !== 'right' || t.starts !== 1) throw new Error('Unexpected thread definition');
if (spec.clearance.proposed_total_axial_clearance_mm !== 1) throw new Error('Unexpected built clearance');
if (!/s = -lead \* phi/.test(k.screw_derived_travel)) throw new Error('Unexpected kinematic sign convention');
const asset = {
  version: 'cutaway-c96', sha256, byteLength: bytes.length,
  prototypeSha256: 'a59025189aad3f957b47dcb7f7075071077b9be8fc80d168a7407edf85843b9c',
  geometry: { leadMm: t.lead_mm, clearanceMm: spec.clearance.proposed_total_axial_clearance_mm, handedness: t.handedness,
    majorDiameterMm: t.major_diameter_mm, minorDiameterMm: t.minor_diameter_mm, flankHalfAngleDeg: t.flank_half_angle_deg,
    radialClearanceMm: spec.clearance.radial_clearance_crest_and_root_mm, nutLengthMm: spec.dimensions_mm.nut_length,
    screwProfile: t.screw_profile_phase_mm_radius_mm, nutProfile: t.nut_profile_phase_mm_radius_mm,
    columnsPerTurn: 96, fullEngagementCarriageMm: spec.dimensions_mm.full_engagement_carriage_x_range },
  status: spec.status, limits: spec.limits,
  base64: bytes.toString('base64')
};
const out = '/* Generated by bake-model-asset.cjs from the original Blender cutaway (build_model.py --cols 96). Do not edit. */\n' +
  '(function(r){var a=' + JSON.stringify(asset) + ';if(typeof module==="object"&&module.exports)module.exports=a;else r.CourseWikiBacklashModel=a;})(typeof globalThis!=="undefined"?globalThis:this);\n';
const file = path.join(__dirname, 'model-asset.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) { console.error('model-asset.js needs regeneration.'); process.exitCode = 1; }
  else console.log('model-asset.js matches ' + sha256);
} else { fs.writeFileSync(file, out); console.log('Cutaway asset: ' + sha256 + '; ' + bytes.length + ' bytes'); }
